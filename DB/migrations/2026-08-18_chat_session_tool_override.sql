-- chat_session.tool_refs_override 추가 (2026-08-18)
--
-- Chat 화면의 "+"(도구·MCP 붙이기)가 에이전트 원본을 건드리지 않고 **이
-- 대화에서만** 도구 구성을 바꿀 수 있게 한다(지훈 확인, 작업기록
-- 2026-08-18_02 §11). 여러 사람이 같은 에이전트(특히 기본 챗)로 동시에
-- 대화할 때, 한 사람이 도구를 껐다고 남의 대화까지 바뀌면 안 된다.
--
-- NULL과 빈 배열을 구분해서 쓴다 — NULL은 "이 대화는 커스터마이즈 안 했다,
-- 에이전트 원래 tool_refs를 그대로 쓴다"는 뜻이고, 빈 배열(`'{}'`)은 "이
-- 대화에서는 도구를 전부 껐다"는 실제 선택이다. 기본값을 안 두는 이유가
-- 이것 — DEFAULT를 주면 그 구분이 사라진다.
-- =====================================================================

BEGIN;

ALTER TABLE chat_session ADD COLUMN IF NOT EXISTS tool_refs_override TEXT[];

COMMIT;

