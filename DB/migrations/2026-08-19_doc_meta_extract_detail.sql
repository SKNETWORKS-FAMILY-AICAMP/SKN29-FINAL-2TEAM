-- 사람이 할 행동이 안 정해진다 —
--
--   「암호가 걸린 PDF 라 열 수 없습니다」  → 암호를 풀어 다시 올리면 된다
--   「텍스트 레이어가 없는 PDF 입니다」    → 다시 올려도 결과가 같다
--   「본문이 너무 짧아 요약할 내용이 없습니다」 → 파일 자체가 짧은 것이다
--
-- 정반대의 행동을 화면이 「본문 추출 실패」 하나로 뭉개고 있었다. 실제로
-- 185자짜리 파일을 두고 「텍스트가 들어 있는 파일로 다시 올려 주세요」라고
-- 안내해 사용자를 틀린 방향으로 보낸 적이 있다(2026-08-18 QA).
--
-- **추출기는 이 문구들을 이미 만들고 있었다**(`services/document_meta/
-- extractor.py` 의 `Extraction.detail`). 담을 칸이 없어 `to_payload()` 에서
-- 그대로 버려지고 있었을 뿐이다 — 새로 계산하는 값이 아니다.
--
-- 기본값을 두지 않는다. OK 인 문서는 이 값이 비어 있는 것이 맞고, 빈 문자열을
-- 기본값으로 주면 「사유가 없다」와 「아직 안 채웠다」가 구분되지 않는다.
