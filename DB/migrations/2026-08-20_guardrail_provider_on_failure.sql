-- 검사기가 응답하지 않을 때 어떻게 할지 팀이 정한다 (2026-08-20)
--
-- 지금까지는 우리가 일괄로 정했다 — **못 부르면 통과**(fail-open). 외부
-- 검사기가 흔들릴 때마다 채팅이 막히면 가드레일이 장애 원인이 되기 때문이다.
--
-- **그런데 이건 고객이 정할 일이다.** 사내 업무 도구라면 통과가 맞지만, 규제
-- 산업 고객에게는 「검사 못 했는데 그냥 보냈다」가 계약 위반이 될 수 있다.
-- 우리가 대신 임시 검사를 돌리는 것(우리 판단으로 막는 것)은 답이 아니다 —
-- 고객이 동의한 적 없는 기준으로 막는 것이고, 「왜 막혔나」에 답할 수 없다.
--
-- 기본값은 OPEN 이다. 지금 도는 팀들의 동작을 바꾸지 않는다 — 마이그레이션이
-- 조용히 정책을 바꾸면 안 된다.
-- =====================================================================

BEGIN;

ALTER TABLE guardrail_provider
    ADD COLUMN IF NOT EXISTS on_failure VARCHAR(10) NOT NULL DEFAULT 'OPEN';

COMMIT;

