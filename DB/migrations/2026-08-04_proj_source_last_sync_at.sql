-- =====================================================================
-- 2026-08-04 | proj_source 에 마지막 수집 시각 추가
--
-- 왜: 프로젝트 목록에 「갱신」 버튼을 두는데, 언제 읽은 값을 보고 있는지
--     알 수 없으면 누를지 말지 판단할 근거가 없다. sync_status 는 'PENDING'
--     에서 움직이지 않아 시각을 대신하지 못한다.
--
-- 실행 위치: DBeaver, 대상 DB의 public 스키마
-- 전제: 없다.
--
-- 기본값을 걸지 않는 이유:
--     now() 를 기본값으로 주면 한 번도 안 읽은 소스가 "방금 읽은 것"이 된다.
--     아직 안 읽은 것과 읽었는데 0건인 것은 다른 상태라서, 전자는 NULL 로 둔다.
--     실제 값은 수집이 성공한 시점에 replace_for_source 가 채운다.
-- =====================================================================

BEGIN;

ALTER TABLE proj_source
    ADD COLUMN last_sync_at TIMESTAMPTZ;

COMMIT;


